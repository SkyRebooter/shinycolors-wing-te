#!/usr/bin/env python3
"""Combine the two source modules into the installable userscript."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VERSION = json.loads((ROOT / 'package.json').read_text())['version']
OUTPUT = ROOT / 'ShinyColorsWing.user.js'
HEADER = f"""// ==UserScript==
// @name         ShinyColors WING TE 助手
// @namespace    local.sc.wing
// @version      {VERSION}
// @description  闪耀色彩日常、活动 Auto 培育排程与 WING TE 单轮助手。
// @match        https://shinycolors.enza.fun/*
// @run-at       document-start
// @grant        none
// @inject-into  page
// @sandbox      raw
// @noframes
// ==/UserScript==
// Generated by scripts/build.py. Edit the files in src/ instead.
"""


def module_source(name):
    text = (ROOT / 'src' / f'{name}.cjs').read_text()
    prefix = 'module.exports = '
    if not text.startswith(prefix) or f"const VERSION = '{VERSION}'" not in text:
        raise SystemExit(f'Invalid {name} module or version mismatch')
    return f'const {name} = {text.removeprefix(prefix).rstrip()}'


def build():
    sources = [module_source(name) for name in ('wing', 'daily')]
    bootstrap = (ROOT / 'src' / 'bootstrap.js').read_text().rstrip()
    return (HEADER + "(() => {\n'use strict';\n\n" + '\n\n'.join(sources) +
            f"\n\n{bootstrap}\n\n" +
            "if (typeof module === 'object' && module.exports) module.exports = { ...wing, daily };\n"
            "else if (typeof window !== 'undefined') startSuite(window, wing, daily);\n})();\n")


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='verify the checked-in userscript matches the build')
    args = parser.parse_args()
    generated = build()
    if args.check:
        if OUTPUT.read_bytes() != generated.encode('utf-8'):
            raise SystemExit('Userscript is out of date. Run python3 scripts/build.py.')
    else:
        OUTPUT.write_bytes(generated.encode('utf-8'))
